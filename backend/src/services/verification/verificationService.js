// Latest submission of each type for each user (one query), the users'
// suspension flags, and whether an upheld report exists against them.
//
// "Upheld report": fraud_reports has no separate "upheld" status today. An
// admin-resolved report (status = 'resolved') is the one that was acted on;
// 'dismissed' and still-open reports do not count. When the reporting phase
// introduces an explicit upheld outcome, change HAS_UPHELD_REPORT_SQL below.
const HAS_UPHELD_REPORT_SQL =
  "SELECT DISTINCT target_user_id AS user_id FROM fraud_reports WHERE target_user_id IN (?) AND status = 'resolved'";

// Returns Map<userId, { identity, donation_evidence, level }> where identity /
// donation_evidence are the latest submission row (or null).
export async function getVerificationStates(userIds, exec = pool) {
  const ids = [...new Set(userIds.map(Number))];
  const states = new Map();
  if (ids.length === 0) return states;

  const [latestRows] = await exec.query(
    `SELECT s.id, s.user_id, s.type, s.status, s.donation_date, s.facility_name,
            s.submitted_at, s.reviewed_at, s.decision_reason,
            s.revoked_at, s.revocation_reason
       FROM verification_submissions s
       JOIN (
         SELECT user_id, type, MAX(id) AS max_id
           FROM verification_submissions
          WHERE user_id IN (?)
          GROUP BY user_id, type
       ) m ON m.max_id = s.id`,
    [ids]
  );
  const [userRows] = await exec.query(
    'SELECT id, is_suspended FROM users WHERE id IN (?)',
    [ids]
  );
  const [reportRows] = await exec.query(HAS_UPHELD_REPORT_SQL, [ids]);

  const suspended = new Map(userRows.map((u) => [u.id, Boolean(u.is_suspended)]));
  const reported = new Set(reportRows.map((r) => r.user_id));

  for (const id of ids) {
    states.set(id, { identity: null, donation_evidence: null, level: 1 });
  }
  for (const row of latestRows) {
    const state = states.get(row.user_id);
    if (state) state[row.type] = row;
  }
  for (const [id, state] of states) {
    state.level = computeVerificationLevel({
      identityStatus: state.identity?.status ?? null,
      donationEvidenceStatus: state.donation_evidence?.status ?? null,
      isSuspended: suspended.get(id) ?? false,
      hasUpheldReport: reported.has(id),
    });
  }
  return states;
}

// Display summaries ({ level, badge, label, identity_verified, ... }) for many
// users, derived from the same rows and rules as getVerificationStates().
// Returns Map<userId, summary>. Users with no records are 'registered'.
export async function getVerificationSummaries(userIds, exec = pool) {
  const states = await getVerificationStates(userIds, exec);
  const summaries = new Map();
  for (const [id, state] of states) summaries.set(id, describeVerification(state.level));
  return summaries;
}

// Server-side gate for every donor action that takes part in a donation
// (accepting a request, moving a commitment forward, recording a donation
// against a request). The level is derived from the database rows, exactly as
// the badge and the Verification page derive it, so nothing the client sends
// can satisfy it. Throws 403 below Level 3; returns the level otherwise.
// Pass the open transaction connection as `exec` to read inside it.
export async function assertDonorMeetsDonationLevel(donorId, exec = pool) {
  const state = (await getVerificationStates([donorId], exec)).get(Number(donorId));
  const level = state ? state.level : 1;
  if (!meetsDonationLevel(level)) {
    throw httpError(403, DONATION_LEVEL_REQUIRED_MESSAGE);
  }
  return level;
}

async function loadFilesBySubmission(submissionIds, exec = pool) {
  const map = new Map();
  if (submissionIds.length === 0) return map;
  const [rows] = await exec.query(
    `SELECT submission_id, storage_key, content_type, size_bytes, created_at
       FROM verification_files
      WHERE submission_id IN (?)
      ORDER BY id ASC`,
    [submissionIds]
  );
  for (const r of rows) {
    if (!map.has(r.submission_id)) map.set(r.submission_id, []);
    map.get(r.submission_id).push({
      key: r.storage_key,
      content_type: r.content_type,
      size_bytes: r.size_bytes,
      created_at: r.created_at,
    });
  }
  return map;
}

function shapeSubmission(row, files) {
  return {
    id: row.id,
    type: row.type,
    status: row.status,
    donation_date: row.donation_date || null,
    facility_name: row.facility_name || null,
    submitted_at: row.submitted_at,
    reviewed_at: row.reviewed_at || null,
    decision_reason: row.decision_reason || null,
    revoked_at: row.revoked_at || null,
    revocation_reason: row.revocation_reason || null,
    files: files || [],
  };
}

// Everything the donor verification screen needs.
export async function getMyVerification(userId) {
  const state = (await getVerificationStates([userId])).get(Number(userId));

  const [historyRows] = await pool.query(
    `SELECT id, type, status, donation_date, facility_name, submitted_at,
            reviewed_at, decision_reason, revoked_at, revocation_reason
       FROM verification_submissions
      WHERE user_id = ?
      ORDER BY id DESC
      LIMIT 20`,
    [userId]
  );
  const files = await loadFilesBySubmission(historyRows.map((r) => r.id));
  const history = historyRows.map((r) => shapeSubmission(r, files.get(r.id)));

  const latest = (type) => {
    const row = state[type];
    return row ? history.find((h) => h.id === row.id) || shapeSubmission(row, []) : null;
  };

  return {
    level: state.level,
    verification: describeVerification(state.level),
    level_label: LEVEL_INFO[state.level].label,
    level_description: LEVEL_INFO[state.level].description,
    levels: Object.entries(LEVEL_INFO).map(([level, info]) => ({
      level: Number(level),
      label: info.label,
      description: info.description,
    })),
    identity: latest('identity'),
    donation_evidence: latest('donation_evidence'),
    can_submit: submissionPermissions({
      identityStatus: state.identity?.status ?? null,
      donationEvidenceStatus: state.donation_evidence?.status ?? null,
    }),
    history,
    limits: {
      max_file_bytes: MAX_FILE_BYTES,
      max_files: MAX_FILES_PER_SUBMISSION,
      allowed_types: ['image/jpeg', 'image/png', 'image/webp', 'application/pdf'],
    },
    notice: VERIFICATION_NOTICE,
  };
}

