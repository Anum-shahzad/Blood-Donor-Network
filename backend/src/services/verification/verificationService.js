// Database-backed verification logic: submissions, private documents, admin
// review, and the derived verification level.
//
// Hard rules enforced here (never in the client):
//   * A level is computed from rows (computeVerificationLevel), never stored.
//   * Every file is identified by its content signature, capped at 5 MB, and
//     stored under a random server-generated name.
//   * A document is only ever returned to its owner or to an admin.
//   * Every state change runs in one transaction that first locks the user's
//     row, so a donor submitting and an admin deciding can't interleave.
import crypto from 'crypto';
import { pool } from '../../config/db.js';
import { validateDonationDate } from '../../utils/validation.js';
import { detectFileType, ALLOWED_TYPES_LABEL } from './fileSignatures.js';
import {
  SUBMISSION_TYPES,
  SUBMISSION_STATUSES,
  MAX_FILE_BYTES,
  MAX_FILES_PER_SUBMISSION,
  MAX_SUBMISSIONS_PER_DAY,
  LEVEL_INFO,
  VERIFICATION_NOTICE,
  DONATION_LEVEL_REQUIRED_MESSAGE,
  meetsDonationLevel,
  computeVerificationLevel,
  describeVerification,
  submissionPermissions,
  validateReason,
} from './verificationRules.js';

function httpError(status, message) {
  const err = new Error(message);
  err.status = status;
  return err;
}

// 48 hex characters + extension, as generated by newStorageKey().
const STORAGE_KEY_PATTERN = /^[a-f0-9]{48}\.(jpg|png|webp|pdf)$/;

function newStorageKey(ext) {
  return `${crypto.randomBytes(24).toString('hex')}.${ext}`;
}

