// Shared with request evidence (services/requestEvidence): same signature check,
// 5 MB cap and random storage key; only the file-count ceiling differs.
export function prepareFiles(files, maxFiles = MAX_FILES_PER_SUBMISSION) {
  if (!Array.isArray(files) || files.length === 0) {
    throw httpError(400, 'Attach at least one document');
  }
  if (files.length > maxFiles) {
    throw httpError(400, `Attach at most ${maxFiles} files`);
  }
  return files.map((f) => {
    const buffer = f?.buffer;
    if (!Buffer.isBuffer(buffer) || buffer.length === 0) {
      throw httpError(400, 'One of the files is empty');
    }
    if (buffer.length > MAX_FILE_BYTES) {
      throw httpError(413, 'Each file must be 5 MB or smaller');
    }
    const detected = detectFileType(buffer);
    if (!detected) {
      throw httpError(400, `Unsupported or unreadable file. Upload a ${ALLOWED_TYPES_LABEL} file.`);
    }
    return {
      buffer,
      mime: detected.mime,
      storageKey: newStorageKey(detected.ext),
      sha256: crypto.createHash('sha256').update(buffer).digest('hex'),
    };
  });
}

export async function submitDocuments(userId, type, files, meta = {}) {
  if (!SUBMISSION_TYPES.includes(type)) throw httpError(400, 'Invalid submission type');

  const prepared = prepareFiles(files);

  let donationDate = null;
  let facilityName = null;
  if (type === 'donation_evidence') {
    const dateError = validateDonationDate(meta.donation_date, 'donation_date');
    if (dateError) throw httpError(400, dateError);
    donationDate = meta.donation_date;

    const facility = typeof meta.facility_name === 'string' ? meta.facility_name.trim() : '';
    if (facility.length < 2 || facility.length > 190) {
      throw httpError(400, 'facility_name is required (2-190 characters)');
    }
    facilityName = facility;
  }

  const conn = await pool.getConnection();
  try {
    await conn.beginTransaction();

    // Serialize everything for this user (see file header).
    await conn.query('SELECT id FROM users WHERE id = ? FOR UPDATE', [userId]);

    const state = (await getVerificationStates([userId], conn)).get(Number(userId));
    const identityStatus = state.identity?.status ?? null;
    const evidenceStatus = state.donation_evidence?.status ?? null;
    const allowed = submissionPermissions({ identityStatus, donationEvidenceStatus: evidenceStatus });

    if (!allowed[type]) {
      if (type === 'identity') {
        throw httpError(
          409,
          identityStatus === 'approved'
            ? 'Your identity is already approved.'
            : 'Your identity document is already waiting for review.'
        );
      }
      if (identityStatus !== 'approved') {
        throw httpError(409, 'Your identity must be approved before you can submit donation evidence.');
      }
      throw httpError(
        409,
        evidenceStatus === 'approved'
          ? 'Your donation evidence is already approved.'
          : 'Your donation evidence is already waiting for review.'
      );
    }

    const [[recent]] = await conn.query(
      'SELECT COUNT(*) AS n FROM verification_submissions WHERE user_id = ? AND submitted_at >= NOW() - INTERVAL 1 DAY',
      [userId]
    );
    if (Number(recent.n) >= MAX_SUBMISSIONS_PER_DAY) {
      throw httpError(429, 'Too many submissions today. Please try again tomorrow.');
    }

    const [result] = await conn.query(
      `INSERT INTO verification_submissions (user_id, type, status, donation_date, facility_name)
       VALUES (?, ?, 'pending', ?, ?)`,
      [userId, type, donationDate, facilityName]
    );
    const submissionId = result.insertId;

    for (const f of prepared) {
      await conn.query(
        `INSERT INTO verification_files
           (submission_id, storage_key, content_type, size_bytes, sha256, data)
         VALUES (?, ?, ?, ?, ?, ?)`,
        [submissionId, f.storageKey, f.mime, f.buffer.length, f.sha256, f.buffer]
      );
    }

    await conn.commit();
    return { id: submissionId, type, status: 'pending' };
  } catch (err) {
    await conn.rollback();
    throw err;
  } finally {
    conn.release();
  }
}

