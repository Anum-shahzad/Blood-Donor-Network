export async function listSubmissionsForAdmin({ status = 'pending', type = null } = {}) {
  if (status !== 'all' && !SUBMISSION_STATUSES.includes(status)) {
    throw httpError(400, `status must be one of: all, ${SUBMISSION_STATUSES.join(', ')}`);
  }
  if (type && !SUBMISSION_TYPES.includes(type)) {
    throw httpError(400, `type must be one of: ${SUBMISSION_TYPES.join(', ')}`);
  }

  const where = [];
  const params = [];
  if (status !== 'all') {
    where.push('s.status = ?');
    params.push(status);
  }
  if (type) {
    where.push('s.type = ?');
    params.push(type);
  }

  // The review queue is oldest-first; every other view is newest-first.
  const order = status === 'pending' ? 'ASC' : 'DESC';
  const [rows] = await pool.query(
    `SELECT s.id, s.user_id, s.type, s.status, s.donation_date, s.facility_name,
            s.submitted_at, s.reviewed_at, s.decision_reason,
            s.revoked_at, s.revocation_reason,
            u.name AS user_name, u.email AS user_email, u.city AS user_city,
            dp.blood_group
       FROM verification_submissions s
       JOIN users u ON u.id = s.user_id
       LEFT JOIN donor_profiles dp ON dp.user_id = s.user_id
       ${where.length ? `WHERE ${where.join(' AND ')}` : ''}
       ORDER BY s.submitted_at ${order}, s.id ${order}
       LIMIT 200`,
    params
  );

  const files = await loadFilesBySubmission(rows.map((r) => r.id));
  const states = await getVerificationStates(rows.map((r) => r.user_id));

  const [countRows] = await pool.query(
    'SELECT type, status, COUNT(*) AS n FROM verification_submissions GROUP BY type, status'
  );
  const counts = {};
  for (const t of SUBMISSION_TYPES) {
    counts[t] = Object.fromEntries(SUBMISSION_STATUSES.map((s) => [s, 0]));
  }
  for (const c of countRows) counts[c.type][c.status] = Number(c.n);

  return {
    submissions: rows.map((r) => ({
      ...shapeSubmission(r, files.get(r.id)),
      user: {
        id: r.user_id,
        name: r.user_name,
        email: r.user_email,
        city: r.user_city,
        blood_group: r.blood_group || null,
      },
      user_level: states.get(r.user_id)?.level ?? 1,
      user_level_label: LEVEL_INFO[states.get(r.user_id)?.level ?? 1].label,
    })),
    counts,
  };
}

// Locks the user's row first and then the submission (the same order the
// donor-side submit uses), and returns the submission row.
async function lockSubmission(conn, submissionId) {
  const [pre] = await conn.query('SELECT user_id FROM verification_submissions WHERE id = ?', [
    submissionId,
  ]);
  if (!pre[0]) throw httpError(404, 'Submission not found');
  await conn.query('SELECT id FROM users WHERE id = ? FOR UPDATE', [pre[0].user_id]);
  const [rows] = await conn.query('SELECT * FROM verification_submissions WHERE id = ? FOR UPDATE', [
    submissionId,
  ]);
  if (!rows[0]) throw httpError(404, 'Submission not found');
  return rows[0];
}

async function decide(submissionId, work) {
  const conn = await pool.getConnection();
  let userId;
  try {
    await conn.beginTransaction();
    const row = await lockSubmission(conn, submissionId);
    userId = row.user_id;
    await work(conn, row);
    await conn.commit();
  } catch (err) {
    await conn.rollback();
    throw err;
  } finally {
    conn.release();
  }
  const state = (await getVerificationStates([userId])).get(Number(userId));
  return { id: Number(submissionId), user_id: userId, user_level: state.level };
}

export async function approveSubmission(submissionId, adminId) {
  const result = await decide(submissionId, async (conn, row) => {
    if (row.status !== 'pending') {
      throw httpError(409, `This submission is already ${row.status}`);
    }
    if (row.type === 'donation_evidence') {
      const state = (await getVerificationStates([row.user_id], conn)).get(row.user_id);
      if (state.identity?.status !== 'approved') {
        throw httpError(409, "Approve this donor's identity before approving donation evidence");
      }
    }
    await conn.query(
      `UPDATE verification_submissions
          SET status = 'approved', reviewed_by = ?, reviewed_at = NOW(), decision_reason = NULL
        WHERE id = ?`,
      [adminId, submissionId]
    );
  });
  return { ...result, status: 'approved' };
}

export async function rejectSubmission(submissionId, adminId, reason) {
  const reasonError = validateReason(reason);
  if (reasonError) throw httpError(400, reasonError);

  const result = await decide(submissionId, async (conn, row) => {
    if (row.status !== 'pending') {
      throw httpError(409, `This submission is already ${row.status}`);
    }
    await conn.query(
      `UPDATE verification_submissions
          SET status = 'rejected', reviewed_by = ?, reviewed_at = NOW(), decision_reason = ?
        WHERE id = ?`,
      [adminId, reason.trim(), submissionId]
    );
  });
  return { ...result, status: 'rejected' };
}

// Revokes a previously APPROVED submission. Revoking an identity approval also
// revokes that donor's approved donation evidence in the same transaction:
// the evidence was accepted on the strength of that identity.
export async function revokeSubmission(submissionId, adminId, reason) {
  const reasonError = validateReason(reason);
  if (reasonError) throw httpError(400, reasonError);

  const result = await decide(submissionId, async (conn, row) => {
    if (row.status !== 'approved') {
      throw httpError(409, 'Only an approved submission can be revoked');
    }
    await conn.query(
      `UPDATE verification_submissions
          SET status = 'revoked', revoked_by = ?, revoked_at = NOW(), revocation_reason = ?
        WHERE id = ?`,
      [adminId, reason.trim(), submissionId]
    );
    if (row.type === 'identity') {
      await conn.query(
        `UPDATE verification_submissions
            SET status = 'revoked', revoked_by = ?, revoked_at = NOW(), revocation_reason = ?
          WHERE user_id = ? AND type = 'donation_evidence' AND status = 'approved'`,
        [adminId, 'Revoked automatically because the identity approval was revoked.', row.user_id]
      );
    }
  });
  return { ...result, status: 'revoked' };
}
